/* eslint-disable sonarjs/no-os-command-from-path -- this dev generator invokes the Go toolchain from PATH */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const moduleDir = execFileSync(
  'go',
  ['list', '-m', '-f', '{{.Dir}}', 'mvdan.cc/sh/v3'],
  {
    encoding: 'utf8',
  },
).trim()
const src = fs.readFileSync(`${moduleDir}/syntax/nodes.go`, 'utf8')
const structs = new Map()
for (const m of src.matchAll(/type (\w+) struct \{(.*?)\n\}/gs)) {
  const fields = []
  for (let line of m[2].split('\n')) {
    // eslint-disable-next-line sonarjs/super-linear-regex -- parses one known, trusted Go source file
    line = line.replace(/\/\/.*$/, '').trim()
    if (!line) {
      continue
    }
    const parts = line.split(/\s+/)
    if (parts.length < 2) {
      continue
    }
    const type = parts.pop()
    for (const name of parts
      .join(' ')
      .split(',')
      .map(s => s.trim())
      .filter(Boolean)) {
      fields.push({ name, type })
    }
  }
  structs.set(m[1], fields)
}
const implementors = new Map()
for (const m of src.matchAll(/func \(\*(\w+)\) (\w+)\(\)\s*\{\}/g)) {
  const [, type, method] = m
  if (!implementors.has(method)) {
    implementors.set(method, [])
  }
  implementors.get(method).push(type)
}
const nodeTypes = new Set()
for (const m of src.matchAll(/func \(\w+ \*(\w+)\) (?:Pos|End)\(\) Pos/g)) {
  nodeTypes.add(m[1])
}
const ifaceMethod = {
  Command: 'commandNode',
  WordPart: 'wordPartNode',
  Loop: 'loopNode',
  ArithmExpr: 'arithmExprNode',
  TestExpr: 'testExprNode',
}
const ifaceTypes = Object.fromEntries(
  Object.entries(ifaceMethod).map(([k, v]) => [k, implementors.get(v) || []]),
)
const ifaceNames = new Set(Object.keys(ifaceMethod))
const helperStructs = new Set(['Slice', 'Replace', 'Expansion'])
const allStructs = [...structs.keys()].filter(n => n !== 'Pos')
const fname = t => 'encode' + t
const jsName = name => {
  if (name === 'Last') {
    return 'lastComments'
  }
  if (name === 'CondLast') {
    return 'condComments'
  }
  if (name === 'ThenLast') {
    return 'thenComments'
  }
  if (name === 'DoLast') {
    return 'doComments'
  }
  return name.charAt(0).toLowerCase() + name.slice(1)
}

const lines = []
const push = (...xs) => lines.push(...xs)
push(
  '// Code generated by scripts/gen-encoder.mjs; DO NOT EDIT.',
  'package processor',
  '',
  'import (',
  '\t"bytes"',
  '\t"io"',
  '',
  '\t"mvdan.cc/sh/v3/syntax"',
  ')',
  '',
)
push(`func writeNodeStart(buf *bytes.Buffer, typeName string, pos, end syntax.Pos) {
	buf.WriteByte('{')
	buf.WriteString(\`"type":\`)
	writeString(buf, typeName)
	buf.WriteString(\`,"start":\`)
	writeUint(buf, uint64(pos.Offset()))
	buf.WriteString(\`,"end":\`)
	writeUint(buf, uint64(end.Offset()))
}
`)
push(`func writeKeyFirst(buf *bytes.Buffer, name string, first *bool) {
	if !*first {
		buf.WriteByte(',')
	}
	*first = false
	buf.WriteByte('"')
	buf.WriteString(name)
	buf.WriteString(\`":\`)
}
`)
push(`func writeBool(buf *bytes.Buffer, value bool) {
	if value {
		buf.WriteString("true")
	} else {
		buf.WriteString("false")
	}
}
`)

function value(type, expr, force = 'false') {
  if (type === 'string') {
    return `writeString(buf, ${expr})`
  }
  if (type === 'bool') {
    return `writeBool(buf, ${expr})`
  }
  if (type === 'Pos') {
    return `writePos(buf, ${expr})`
  }
  if (type.startsWith('[]')) {
    const el = type.slice(2)
    if (el.startsWith('*')) {
      const t = el.slice(1)
      return `buf.WriteByte('['); for i, item := range ${expr} { if i > 0 { buf.WriteByte(',') }; if item == nil { buf.WriteString("null") } else { ${fname(t)}(buf, item, false) } }; buf.WriteByte(']')`
    }
    if (ifaceNames.has(el)) {
      return `buf.WriteByte('['); for i, item := range ${expr} { if i > 0 { buf.WriteByte(',') }; ${fname(el)}(buf, item, true) }; buf.WriteByte(']')`
    }
    return `buf.WriteByte('['); for i := range ${expr} { if i > 0 { buf.WriteByte(',') }; ${fname(el)}(buf, &${expr}[i], false) }; buf.WriteByte(']')`
  }
  if (type.startsWith('*')) {
    const t = type.slice(1)
    if (nodeTypes.has(t)) {
      return `if ${expr} == nil { buf.WriteString("null") } else { ${fname(t)}(buf, ${expr}, ${force}) }`
    }
    return `if ${expr} == nil { buf.WriteString("null") } else { ${fname(t)}(buf, ${expr}) }`
  }
  if (ifaceNames.has(type)) {
    return `${fname(type)}(buf, ${expr}, true)`
  }
  return `writeUint(buf, uint64(${expr}))`
}

for (const t of allStructs) {
  const fields = structs.get(t)
  const isNode = nodeTypes.has(t)
  const isHelper = helperStructs.has(t)
  push(
    `func ${fname(t)}(buf *bytes.Buffer, v *syntax.${t}${isHelper ? '' : ', force bool'}) {`,
  )
  if (isNode) {
    push(`\twriteNodeStart(buf, "${t}", v.Pos(), v.End())`)
    push('\tfirst := false')
  } else {
    push("\tbuf.WriteByte('{')")
    push('\tfirst := true')
  }
  for (const f of fields) {
    push(`\twriteKeyFirst(buf, "${jsName(f.name)}", &first)`)
    const fieldExpr = `v.${f.name}`
    push(`\t${value(f.type, fieldExpr)}`)
  }
  push("\tbuf.WriteByte('}')")
  push('}')
  push('')
}

for (const [iface, types] of Object.entries(ifaceTypes)) {
  push(
    `func ${fname(iface)}(buf *bytes.Buffer, v syntax.${iface}, force bool) {`,
  )
  push('\tif v == nil { buf.WriteString("null"); return }')
  push('\tswitch v := v.(type) {')
  for (const t of types) {
    push(`\tcase *syntax.${t}: ${fname(t)}(buf, v, force)`)
  }
  push('\tdefault: buf.WriteString("null")')
  push('\t}')
  push('}')
  push('')
}

push('// EncodeNode writes node as typed JSON.')
push('func EncodeNode(w io.Writer, node syntax.Node) error {')
push('\tvar buf bytes.Buffer')
push('\tswitch node := node.(type) {')
for (const t of allStructs) {
  if (nodeTypes.has(t)) {
    push(`\tcase *syntax.${t}: ${fname(t)}(&buf, node, true)`)
  }
}
push('\tdefault: buf.WriteString("null")')
push('\t}')
push('\t_, err := w.Write(buf.Bytes())')
push('\treturn err')
push('}')
const output = `${root}/processor/encode_generated.go`
fs.writeFileSync(output, lines.join('\n') + '\n')
execFileSync('gofmt', ['-w', output], { stdio: 'inherit' })
