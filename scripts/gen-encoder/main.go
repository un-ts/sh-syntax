// Command gen-encoder generates processor/encode_generated.go from the
// mvdan.cc/sh syntax node definitions.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
)

type field struct {
	name string
	typ  string
}

type typeInfo struct {
	fields []field
	isNode bool
}

var interfaceMethods = map[string]string{
	"Command":    "commandNode",
	"WordPart":   "wordPartNode",
	"Loop":       "loopNode",
	"ArithmExpr": "arithmExprNode",
	"TestExpr":   "testExprNode",
}

func main() {
	file := parseNodes()
	structs, order, implementors := collectTypes(file)
	markNodeTypes(structs, implementors)
	allTypes := typeOrder(order)
	interfaces := interfaceImplementations(implementors)

	var buf bytes.Buffer
	writeEncoder(&buf, structs, allTypes, interfaces)

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fatalf("format generated source: %v", err)
	}
	if err := os.WriteFile("processor/encode_generated.go", formatted, 0o644); err != nil {
		fatalf("write encoder: %v", err)
	}
}

func goCommand() string {
	name := "go"
	if runtime.GOOS == "windows" {
		name += ".exe"
	}
	return filepath.Join(runtime.GOROOT(), "bin", name)
}

func parseNodes() *ast.File {
	goBin := goCommand()
	if err := exec.Command(goBin, "mod", "download", "mvdan.cc/sh/v3").Run(); err != nil {
		fatalf("download mvdan.cc/sh/v3: %v", err)
	}
	moduleDir, err := exec.Command(goBin, "list", "-m", "-f", "{{.Dir}}", "mvdan.cc/sh/v3").Output()
	if err != nil {
		fatalf("locate mvdan.cc/sh/v3: %v", err)
	}
	dir := strings.TrimSpace(string(moduleDir))
	if dir == "" {
		fatalf("mvdan.cc/sh/v3 has no module directory")
	}
	nodesPath := filepath.Join(dir, "syntax", "nodes.go")

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, nodesPath, nil, 0)
	if err != nil {
		fatalf("parse %s: %v", nodesPath, err)
	}
	return file
}

func collectTypes(file *ast.File) (map[string]*typeInfo, []string, map[string][]string) {
	structs := make(map[string]*typeInfo)
	var order []string
	implementors := make(map[string][]string)

	for _, decl := range file.Decls {
		switch decl := decl.(type) {
		case *ast.GenDecl:
			collectGenDecl(decl, structs, &order)
		case *ast.FuncDecl:
			collectFuncDecl(decl, structs, implementors)
		}
	}

	return structs, order, implementors
}

func collectGenDecl(decl *ast.GenDecl, structs map[string]*typeInfo, order *[]string) {
	if decl.Tok != token.TYPE {
		return
	}
	for _, spec := range decl.Specs {
		ts, ok := spec.(*ast.TypeSpec)
		if !ok {
			continue
		}
		typ, ok := ts.Type.(*ast.StructType)
		if !ok {
			continue
		}
		info := &typeInfo{}
		for _, f := range typ.Fields.List {
			fieldType := typeString(f.Type)
			for _, name := range f.Names {
				info.fields = append(info.fields, field{name.Name, fieldType})
			}
		}
		structs[ts.Name.Name] = info
		*order = append(*order, ts.Name.Name)
	}
}

func collectFuncDecl(decl *ast.FuncDecl, structs map[string]*typeInfo, implementors map[string][]string) {
	if decl.Recv == nil {
		return
	}
	recv := receiverName(decl.Recv.List[0].Type)
	if recv == "" {
		return
	}
	implementors[decl.Name.Name] = append(implementors[decl.Name.Name], recv)
}

func markNodeTypes(structs map[string]*typeInfo, implementors map[string][]string) {
	for _, method := range []string{"Pos", "End"} {
		for _, impl := range implementors[method] {
			if info := structs[impl]; info != nil {
				info.isNode = true
			}
		}
	}
}

func typeOrder(order []string) []string {
	allTypes := make([]string, 0, len(order))
	for _, name := range order {
		if name != "Pos" {
			allTypes = append(allTypes, name)
		}
	}
	return allTypes
}

func interfaceImplementations(implementors map[string][]string) map[string][]string {
	interfaces := make(map[string][]string)
	for name, method := range interfaceMethods {
		interfaces[name] = implementors[method]
	}
	return interfaces
}

func writeEncoder(buf *bytes.Buffer, structs map[string]*typeInfo, allTypes []string, interfaces map[string][]string) {
	fmt.Fprintln(buf, "// Code generated by scripts/gen-encoder; DO NOT EDIT.")
	fmt.Fprintln(buf, "package processor")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, "import (")
	fmt.Fprintln(buf, "\t\"bytes\"")
	fmt.Fprintln(buf, "\t\"io\"")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, "\t\"mvdan.cc/sh/v3/syntax\"")
	fmt.Fprintln(buf, ")")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, `func writeNodeStart(buf *bytes.Buffer, typeName string, pos, end syntax.Pos) {
	buf.WriteByte('{')
	buf.WriteString(`+"`\"type\":`"+`)
	writeString(buf, typeName)
	buf.WriteString(`+"`,\"start\":`"+`)
	writeUint(buf, uint64(pos.Offset()))
	buf.WriteString(`+"`,\"end\":`"+`)
	writeUint(buf, uint64(end.Offset()))
}`)
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, `func writeKeyFirst(buf *bytes.Buffer, name string, first *bool) {
	if !*first {
		buf.WriteByte(',')
	}
	*first = false
	buf.WriteByte('"')
	buf.WriteString(name)
	buf.WriteString(`+"`\":`"+`)
}`)
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, `func writeBool(buf *bytes.Buffer, value bool) {
	if value {
		buf.WriteString("true")
	} else {
		buf.WriteString("false")
	}
}`)
	fmt.Fprintln(buf)

	for _, name := range allTypes {
		info := structs[name]
		fmt.Fprintf(buf, "func encode%s(buf *bytes.Buffer, v *syntax.%s) {\n", name, name)
		if info.isNode {
			fmt.Fprintf(buf, "\twriteNodeStart(buf, %q, v.Pos(), v.End())\n", name)
			fmt.Fprintln(buf, "\tfirst := false")
		} else {
			fmt.Fprintln(buf, "\tbuf.WriteByte('{')")
			fmt.Fprintln(buf, "\tfirst := true")
		}
		for _, f := range info.fields {
			fmt.Fprintf(buf, "\twriteKeyFirst(buf, %q, &first)\n", jsName(f.name))
			fmt.Fprintf(buf, "\t%s\n", valueExpr(f.typ, "v."+f.name, interfaces))
		}
		fmt.Fprintln(buf, "\tbuf.WriteByte('}')")
		fmt.Fprintln(buf, "}")
		fmt.Fprintln(buf)
	}

	for _, name := range []string{"Command", "WordPart", "Loop", "ArithmExpr", "TestExpr"} {
		types := interfaces[name]
		fmt.Fprintf(buf, "func encode%s(buf *bytes.Buffer, v syntax.%s) {\n", name, name)
		fmt.Fprintln(buf, "\tif v == nil { buf.WriteString(\"null\"); return }")
		fmt.Fprintln(buf, "\tswitch v := v.(type) {")
		for _, typ := range types {
			fmt.Fprintf(buf, "\tcase *syntax.%s: encode%s(buf, v)\n", typ, typ)
		}
		fmt.Fprintln(buf, "\tdefault: buf.WriteString(\"null\")")
		fmt.Fprintln(buf, "\t}")
		fmt.Fprintln(buf, "}")
		fmt.Fprintln(buf)
	}

	fmt.Fprintln(buf, "// EncodeNode writes node as typed JSON.")
	fmt.Fprintln(buf, "func EncodeNode(w io.Writer, node syntax.Node) error {")
	fmt.Fprintln(buf, "\tvar buf bytes.Buffer")
	fmt.Fprintln(buf, "\tswitch node := node.(type) {")
	for _, name := range allTypes {
		if !structs[name].isNode {
			continue
		}
		fmt.Fprintf(buf, "\tcase *syntax.%s: encode%s(&buf, node)\n", name, name)
	}
	fmt.Fprintln(buf, "\tdefault: buf.WriteString(\"null\")")
	fmt.Fprintln(buf, "\t}")
	fmt.Fprintln(buf, "\t_, err := w.Write(buf.Bytes())")
	fmt.Fprintln(buf, "\treturn err")
	fmt.Fprintln(buf, "}")
}

func typeString(expr ast.Expr) string {
	switch expr := expr.(type) {
	case *ast.Ident:
		return expr.Name
	case *ast.StarExpr:
		return "*" + typeString(expr.X)
	case *ast.ArrayType:
		return "[]" + typeString(expr.Elt)
	case *ast.SelectorExpr:
		return typeString(expr.X) + "." + expr.Sel.Name
	default:
		panic(fmt.Sprintf("unsupported type %T", expr))
	}
}

func receiverName(expr ast.Expr) string {
	if star, ok := expr.(*ast.StarExpr); ok {
		return typeString(star.X)
	}
	return typeString(expr)
}

func jsName(name string) string {
	switch name {
	case "Last":
		return "lastComments"
	case "CondLast":
		return "condComments"
	case "ThenLast":
		return "thenComments"
	case "DoLast":
		return "doComments"
	default:
		return strings.ToLower(name[:1]) + name[1:]
	}
}

func valueExpr(typ, expr string, interfaces map[string][]string) string {
	switch {
	case typ == "string":
		return fmt.Sprintf("writeString(buf, %s)", expr)
	case typ == "bool":
		return fmt.Sprintf("writeBool(buf, %s)", expr)
	case typ == "Pos":
		return fmt.Sprintf("writePos(buf, %s)", expr)
	case strings.HasPrefix(typ, "[]"):
		el := strings.TrimPrefix(typ, "[]")
		if strings.HasPrefix(el, "*") {
			el = strings.TrimPrefix(el, "*")
			return fmt.Sprintf("buf.WriteByte('['); for i, item := range %s { if i > 0 { buf.WriteByte(',') }; if item == nil { buf.WriteString(\"null\") } else { encode%s(buf, item) } }; buf.WriteByte(']')", expr, el)
		}
		if _, ok := interfaces[el]; ok {
			return fmt.Sprintf("buf.WriteByte('['); for i, item := range %s { if i > 0 { buf.WriteByte(',') }; encode%s(buf, item) }; buf.WriteByte(']')", expr, el)
		}
		return fmt.Sprintf("buf.WriteByte('['); for i := range %s { if i > 0 { buf.WriteByte(',') }; encode%s(buf, &%s[i]) }; buf.WriteByte(']')", expr, el, expr)
	case strings.HasPrefix(typ, "*"):
		el := strings.TrimPrefix(typ, "*")
		return fmt.Sprintf("if %s == nil { buf.WriteString(\"null\") } else { encode%s(buf, %s) }", expr, el, expr)
	default:
		if _, ok := interfaces[typ]; ok {
			return fmt.Sprintf("encode%s(buf, %s)", typ, expr)
		}
		return fmt.Sprintf("writeUint(buf, uint64(%s))", expr)
	}
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
