// Command gen-encoder generates processor/encode_generated.go from the
// mvdan.cc/sh syntax node definitions.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"sort"
	"strconv"
	"strings"
)

type field struct {
	name string
	typ  string
}

type typeInfo struct {
	fields []field
	isNode bool
}

var interfaceMethods = map[string]string{
	"Command":    "commandNode",
	"WordPart":   "wordPartNode",
	"Loop":       "loopNode",
	"ArithmExpr": "arithmExprNode",
	"TestExpr":   "testExprNode",
}

func main() {
	file, moduleDir := parseNodes()
	structs, order, implementors := collectTypes(file)
	markNodeTypes(structs, implementors)
	allTypes := typeOrder(order)
	interfaces := interfaceImplementations(implementors)
	operators := loadOperators(moduleDir)

	var buf bytes.Buffer
	writeEncoder(&buf, structs, allTypes, interfaces)
	writeTypes(structs, order, interfaces, operators)
	writeOperators(operators)

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fatalf("format generated encoder source: %v", err)
	}
	if err := os.WriteFile("processor/encode_generated.go", formatted, 0o644); err != nil {
		fatalf("write encoder: %v", err)
	}

	var decoder bytes.Buffer
	writeDecoder(&decoder, structs, allTypes, interfaces, operators)
	formatted, err = format.Source(decoder.Bytes())
	if err != nil {
		fatalf("format generated decoder source: %v", err)
	}
	if err := os.WriteFile("processor/decode_generated.go", formatted, 0o644); err != nil {
		fatalf("write decoder: %v", err)
	}

	var patcher bytes.Buffer
	writePatcher(&patcher, structs, allTypes, operators)
	formatted, err = format.Source(patcher.Bytes())
	if err != nil {
		fatalf("format generated patcher source: %v", err)
	}
	if err := os.WriteFile("processor/patch_generated.go", formatted, 0o644); err != nil {
		fatalf("write patcher: %v", err)
	}
}

func goCommand() string {
	name := "go"
	if runtime.GOOS == "windows" {
		name += ".exe"
	}
	return filepath.Join(runtime.GOROOT(), "bin", name)
}

func parseNodes() (*ast.File, string) {
	goBin := goCommand()
	if err := exec.Command(goBin, "mod", "download", "mvdan.cc/sh/v3").Run(); err != nil {
		fatalf("download mvdan.cc/sh/v3: %v", err)
	}
	moduleDir, err := exec.Command(goBin, "list", "-m", "-f", "{{.Dir}}", "mvdan.cc/sh/v3").Output()
	if err != nil {
		fatalf("locate mvdan.cc/sh/v3: %v", err)
	}
	dir := strings.TrimSpace(string(moduleDir))
	if dir == "" {
		fatalf("mvdan.cc/sh/v3 has no module directory")
	}
	nodesPath := filepath.Join(dir, "syntax", "nodes.go")

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, nodesPath, nil, 0)
	if err != nil {
		fatalf("parse %s: %v", nodesPath, err)
	}
	return file, dir
}

func collectTypes(file *ast.File) (map[string]*typeInfo, []string, map[string][]string) {
	structs := make(map[string]*typeInfo)
	var order []string
	implementors := make(map[string][]string)

	for _, decl := range file.Decls {
		switch decl := decl.(type) {
		case *ast.GenDecl:
			collectGenDecl(decl, structs, &order)
		case *ast.FuncDecl:
			collectFuncDecl(decl, structs, implementors)
		}
	}

	return structs, order, implementors
}

func collectGenDecl(decl *ast.GenDecl, structs map[string]*typeInfo, order *[]string) {
	if decl.Tok != token.TYPE {
		return
	}
	for _, spec := range decl.Specs {
		ts, ok := spec.(*ast.TypeSpec)
		if !ok {
			continue
		}
		typ, ok := ts.Type.(*ast.StructType)
		if !ok {
			continue
		}
		info := &typeInfo{}
		for _, f := range typ.Fields.List {
			fieldType := typeString(f.Type)
			for _, name := range f.Names {
				info.fields = append(info.fields, field{name.Name, fieldType})
			}
		}
		structs[ts.Name.Name] = info
		*order = append(*order, ts.Name.Name)
	}
}

func collectFuncDecl(decl *ast.FuncDecl, structs map[string]*typeInfo, implementors map[string][]string) {
	if decl.Recv == nil {
		return
	}
	recv := receiverName(decl.Recv.List[0].Type)
	if recv == "" {
		return
	}
	implementors[decl.Name.Name] = append(implementors[decl.Name.Name], recv)
}

func markNodeTypes(structs map[string]*typeInfo, implementors map[string][]string) {
	for _, method := range []string{"Pos", "End"} {
		for _, impl := range implementors[method] {
			if info := structs[impl]; info != nil {
				info.isNode = true
			}
		}
	}
}

func typeOrder(order []string) []string {
	allTypes := make([]string, 0, len(order))
	for _, name := range order {
		if name != "Pos" {
			allTypes = append(allTypes, name)
		}
	}
	return allTypes
}

func interfaceImplementations(implementors map[string][]string) map[string][]string {
	interfaces := make(map[string][]string)
	for name, method := range interfaceMethods {
		interfaces[name] = implementors[method]
	}
	return interfaces
}

func writeEncoder(buf *bytes.Buffer, structs map[string]*typeInfo, allTypes []string, interfaces map[string][]string) {
	fmt.Fprintln(buf, "// Code generated by scripts/gen-encoder; DO NOT EDIT.")
	fmt.Fprintln(buf, "package processor")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, "import (")
	fmt.Fprintln(buf, "\t\"bytes\"")
	fmt.Fprintln(buf, "\t\"io\"")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, "\t\"mvdan.cc/sh/v3/syntax\"")
	fmt.Fprintln(buf, ")")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, `func writeNodeStart(buf *bytes.Buffer, typeName string, pos, end syntax.Pos) {
	buf.WriteByte('{')
	buf.WriteString(`+"`\"type\":`"+`)
	writeString(buf, typeName)
	buf.WriteString(`+"`,\"start\":`"+`)
	writeUint(buf, uint64(pos.Offset()))
	buf.WriteString(`+"`,\"end\":`"+`)
	writeUint(buf, uint64(end.Offset()))
}`)
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, `func writeKeyFirst(buf *bytes.Buffer, name string, first *bool) {
	if !*first {
		buf.WriteByte(',')
	}
	*first = false
	buf.WriteByte('"')
	buf.WriteString(name)
	buf.WriteString(`+"`\":`"+`)
}`)
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, `func writeBool(buf *bytes.Buffer, value bool) {
	if value {
		buf.WriteString("true")
	} else {
		buf.WriteString("false")
	}
}`)
	fmt.Fprintln(buf)

	for _, name := range allTypes {
		info := structs[name]
		fmt.Fprintf(buf, "func encode%s(buf *bytes.Buffer, v *syntax.%s) {\n", name, name)
		if info.isNode {
			fmt.Fprintf(buf, "\twriteNodeStart(buf, %q, v.Pos(), v.End())\n", name)
			fmt.Fprintln(buf, "\tfirst := false")
		} else {
			fmt.Fprintln(buf, "\tbuf.WriteByte('{')")
			fmt.Fprintln(buf, "\tfirst := true")
		}
		for _, f := range info.fields {
			fmt.Fprintf(buf, "\twriteKeyFirst(buf, %q, &first)\n", jsName(f.name))
			fmt.Fprintf(buf, "\t%s\n", valueExpr(f.typ, "v."+f.name, interfaces))
		}
		fmt.Fprintln(buf, "\tbuf.WriteByte('}')")
		fmt.Fprintln(buf, "}")
		fmt.Fprintln(buf)
	}

	for _, name := range []string{"Command", "WordPart", "Loop", "ArithmExpr", "TestExpr"} {
		types := interfaces[name]
		fmt.Fprintf(buf, "func encode%s(buf *bytes.Buffer, v syntax.%s) {\n", name, name)
		fmt.Fprintln(buf, "\tif v == nil { buf.WriteString(\"null\"); return }")
		fmt.Fprintln(buf, "\tswitch v := v.(type) {")
		for _, typ := range types {
			fmt.Fprintf(buf, "\tcase *syntax.%s: encode%s(buf, v)\n", typ, typ)
		}
		fmt.Fprintln(buf, "\tdefault: buf.WriteString(\"null\")")
		fmt.Fprintln(buf, "\t}")
		fmt.Fprintln(buf, "}")
		fmt.Fprintln(buf)
	}

	fmt.Fprintln(buf, "// EncodeNode writes node as typed JSON.")
	fmt.Fprintln(buf, "func EncodeNode(w io.Writer, node syntax.Node) error {")
	fmt.Fprintln(buf, "\tvar buf bytes.Buffer")
	fmt.Fprintln(buf, "\tswitch node := node.(type) {")
	for _, name := range allTypes {
		if !structs[name].isNode {
			continue
		}
		fmt.Fprintf(buf, "\tcase *syntax.%s: encode%s(&buf, node)\n", name, name)
	}
	fmt.Fprintln(buf, "\tdefault: buf.WriteString(\"null\")")
	fmt.Fprintln(buf, "\t}")
	fmt.Fprintln(buf, "\t_, err := w.Write(buf.Bytes())")
	fmt.Fprintln(buf, "\treturn err")
	fmt.Fprintln(buf, "}")
}

func writeTypes(structs map[string]*typeInfo, order []string, interfaces map[string][]string, operators map[string]map[string]string) {
	var b strings.Builder
	b.WriteString("// Code generated by scripts/gen-encoder; DO NOT EDIT.\n")
	writeOperatorImport(&b, structs, operators)
	b.WriteString("import type { Pos } from './types.js'\n\n")
	b.WriteString("export interface BaseNode {\n  type: string\n  start: number\n  end: number\n}\n\n")

	for _, name := range order {
		if name != "Pos" {
			writeInterface(&b, name, structs[name], structs, interfaces, operators)
		}
	}

	for _, iface := range []string{"Command", "WordPart", "Loop", "ArithmExpr", "TestExpr"} {
		writeUnion(&b, iface, interfaces[iface])
	}

	writeNodeUnion(&b, order, structs)

	if err := os.WriteFile("src/ast-types.ts", []byte(b.String()), 0o644); err != nil {
		fatalf("write types: %v", err)
	}
}

func writeOperatorImport(b *strings.Builder, structs map[string]*typeInfo, operators map[string]map[string]string) {
	used := map[string]bool{}
	for _, info := range structs {
		for _, f := range info.fields {
			base := strings.TrimPrefix(strings.TrimPrefix(f.typ, "[]"), "*")
			if _, ok := operators[base]; ok {
				used[base] = true
			}
		}
	}
	if len(used) == 0 {
		return
	}
	var names []string
	for name := range used {
		names = append(names, name)
	}
	sort.Strings(names)
	fmt.Fprintf(b, "import type { %s } from './operators.js'\n", strings.Join(names, ", "))
}

func writeInterface(b *strings.Builder, name string, info *typeInfo, structs map[string]*typeInfo, interfaces map[string][]string, operators map[string]map[string]string) {
	fmt.Fprintf(b, "export interface %s", name)
	if info.isNode {
		b.WriteString(" extends BaseNode")
	}
	b.WriteString(" {\n")
	if info.isNode {
		fmt.Fprintf(b, "  type: %q\n", name)
	}
	for _, f := range info.fields {
		fmt.Fprintf(b, "  %s: %s\n", jsName(f.name), tsType(f.typ, structs, interfaces, operators))
	}
	b.WriteString("}\n\n")
}

func writeUnion(b *strings.Builder, name string, types []string) {
	if len(types) == 0 {
		return
	}
	types = append([]string(nil), types...)
	sort.Slice(types, func(i, j int) bool {
		return strings.ToLower(types[i]) < strings.ToLower(types[j])
	})
	fmt.Fprintf(b, "export type %s =\n", name)
	for _, typ := range types {
		fmt.Fprintf(b, "  | %s\n", typ)
	}
	b.WriteString("\n")
}

func writeNodeUnion(b *strings.Builder, order []string, structs map[string]*typeInfo) {
	var names []string
	for _, name := range order {
		if structs[name].isNode {
			names = append(names, name)
		}
	}
	sort.Slice(names, func(i, j int) bool {
		return strings.ToLower(names[i]) < strings.ToLower(names[j])
	})
	b.WriteString("export type Node =\n")
	for _, name := range names {
		fmt.Fprintf(b, "  | %s\n", name)
	}
	b.WriteString("\n")
}

func tsType(typ string, structs map[string]*typeInfo, interfaces map[string][]string, operators map[string]map[string]string) string {
	switch typ {
	case "string":
		return "string"
	case "bool":
		return "boolean"
	case "Pos":
		return "Pos"
	}
	if strings.HasPrefix(typ, "[]") {
		el := strings.TrimPrefix(typ, "[]")
		if strings.HasPrefix(el, "*") {
			el = strings.TrimPrefix(el, "*")
			return tsType(el, structs, interfaces, operators) + "[]"
		}
		if _, ok := interfaces[el]; ok {
			return el + "[]"
		}
		return tsType(el, structs, interfaces, operators) + "[]"
	}
	if strings.HasPrefix(typ, "*") {
		return tsType(strings.TrimPrefix(typ, "*"), structs, interfaces, operators) + " | null"
	}
	if _, ok := interfaces[typ]; ok {
		return typ + " | null"
	}
	if _, ok := operators[typ]; ok {
		return typ
	}
	if _, ok := structs[typ]; ok {
		return typ
	}
	return "number"
}

func loadOperators(dir string) map[string]map[string]string {
	tokensPath := filepath.Join(dir, "syntax", "tokens.go")
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, tokensPath, nil, 0)
	if err != nil {
		fatalf("parse %s: %v", tokensPath, err)
	}
	conf := types.Config{Importer: importer.Default()}
	pkg, _ := conf.Check("mvdan.cc/sh/v3/syntax", fset, []*ast.File{file}, nil)
	if pkg == nil {
		fatalf("type-check %s", tokensPath)
	}
	operators := make(map[string]map[string]string)
	for _, name := range pkg.Scope().Names() {
		obj, ok := pkg.Scope().Lookup(name).(*types.Const)
		if !ok {
			continue
		}
		named, ok := obj.Type().(*types.Named)
		if !ok {
			continue
		}
		typeName := named.Obj().Name()
		if !strings.HasSuffix(typeName, "Operator") {
			continue
		}
		if operators[typeName] == nil {
			operators[typeName] = make(map[string]string)
		}
		operators[typeName][name] = obj.Val().ExactString()
	}
	if operators["ParNamesOperator"] == nil {
		fatalf("missing ParNamesOperator constants")
	}
	operators["ParNamesOperator"]["None"] = "0"
	if len(operators) == 0 {
		fatalf("no operator constants found")
	}
	return operators
}

func writeOperators(operators map[string]map[string]string) {
	var b strings.Builder
	b.WriteString("// Code generated by scripts/gen-encoder; DO NOT EDIT.\n")
	b.WriteString("import type { ValueOf } from './types.js'\n\n")
	var types []string
	for name := range operators {
		types = append(types, name)
	}
	sort.Strings(types)
	for _, typ := range types {
		fmt.Fprintf(&b, "export const %s = {\n", typ)
		var names []string
		for name := range operators[typ] {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			fmt.Fprintf(&b, "  %s: %s,\n", name, operators[typ][name])
		}
		fmt.Fprintf(&b, "} as const\n\nexport type %s = ValueOf<typeof %s>\n\n", typ, typ)
	}
	if err := os.WriteFile("src/operators.ts", []byte(b.String()), 0o644); err != nil {
		fatalf("write operators: %v", err)
	}
}

func typeString(expr ast.Expr) string {
	switch expr := expr.(type) {
	case *ast.Ident:
		return expr.Name
	case *ast.StarExpr:
		return "*" + typeString(expr.X)
	case *ast.ArrayType:
		return "[]" + typeString(expr.Elt)
	case *ast.SelectorExpr:
		return typeString(expr.X) + "." + expr.Sel.Name
	default:
		panic(fmt.Sprintf("unsupported type %T", expr))
	}
}

func receiverName(expr ast.Expr) string {
	if star, ok := expr.(*ast.StarExpr); ok {
		return typeString(star.X)
	}
	return typeString(expr)
}

func jsName(name string) string {
	switch name {
	case "Last":
		return "lastComments"
	case "CondLast":
		return "condComments"
	case "ThenLast":
		return "thenComments"
	case "DoLast":
		return "doComments"
	default:
		return strings.ToLower(name[:1]) + name[1:]
	}
}

func valueExpr(typ, expr string, interfaces map[string][]string) string {
	switch {
	case typ == "string":
		return fmt.Sprintf("writeString(buf, %s)", expr)
	case typ == "bool":
		return fmt.Sprintf("writeBool(buf, %s)", expr)
	case typ == "Pos":
		return fmt.Sprintf("writePos(buf, %s)", expr)
	case strings.HasPrefix(typ, "[]"):
		el := strings.TrimPrefix(typ, "[]")
		if strings.HasPrefix(el, "*") {
			el = strings.TrimPrefix(el, "*")
			return fmt.Sprintf("buf.WriteByte('['); for i, item := range %s { if i > 0 { buf.WriteByte(',') }; if item == nil { buf.WriteString(\"null\") } else { encode%s(buf, item) } }; buf.WriteByte(']')", expr, el)
		}
		if _, ok := interfaces[el]; ok {
			return fmt.Sprintf("buf.WriteByte('['); for i, item := range %s { if i > 0 { buf.WriteByte(',') }; encode%s(buf, item) }; buf.WriteByte(']')", expr, el)
		}
		return fmt.Sprintf("buf.WriteByte('['); for i := range %s { if i > 0 { buf.WriteByte(',') }; encode%s(buf, &%s[i]) }; buf.WriteByte(']')", expr, el, expr)
	case strings.HasPrefix(typ, "*"):
		el := strings.TrimPrefix(typ, "*")
		return fmt.Sprintf("if %s == nil { buf.WriteString(\"null\") } else { encode%s(buf, %s) }", expr, el, expr)
	default:
		if _, ok := interfaces[typ]; ok {
			return fmt.Sprintf("encode%s(buf, %s)", typ, expr)
		}
		return fmt.Sprintf("writeUint(buf, uint64(%s))", expr)
	}
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}

func writeDecoder(buf *bytes.Buffer, structs map[string]*typeInfo, allTypes []string, interfaces map[string][]string, operators map[string]map[string]string) {
	fmt.Fprintln(buf, "// Code generated by scripts/gen-encoder; DO NOT EDIT.")
	fmt.Fprintln(buf, "package processor")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, "import (")
	fmt.Fprintln(buf, "\t\"encoding/json\"")
	fmt.Fprintln(buf, "\t\"fmt\"")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, "\t\"mvdan.cc/sh/v3/syntax\"")
	fmt.Fprintln(buf, ")")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, `func decodeString(raw json.RawMessage) (string, error) {
	var value string
	err := json.Unmarshal(raw, &value)
	return value, err
}`)
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, `func decodeBool(raw json.RawMessage) (bool, error) {
	var value bool
	err := json.Unmarshal(raw, &value)
	return value, err
}`)
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, `func decodeUint(raw json.RawMessage) (uint, error) {
	var value uint
	err := json.Unmarshal(raw, &value)
	return value, err
}`)
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, `func decodeInt(raw json.RawMessage) (int, error) {
	var value int
	err := json.Unmarshal(raw, &value)
	return value, err
}`)
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, `func decodeInteger[T ~int | ~int8 | ~int16 | ~int32 | ~int64 | ~uint | ~uint8 | ~uint16 | ~uint32 | ~uint64](raw json.RawMessage) (T, error) {
	var value T
	err := json.Unmarshal(raw, &value)
	return value, err
}`)
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, `func decodePos(raw json.RawMessage) (syntax.Pos, error) {
	var value struct {
		Offset uint
		Line   uint
		Column uint
	}
	if err := json.Unmarshal(raw, &value); err != nil {
		return syntax.Pos{}, err
	}
	return syntax.NewPos(value.Offset, value.Line, value.Column), nil
}`)
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, `func decodePtr[T any](raw json.RawMessage, decode func(json.RawMessage) (*T, error)) (*T, error) {
	if len(raw) == 0 || string(raw) == "null" {
		return nil, nil
	}
	return decode(raw)
}`)
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, `func decodeList[T any](raw json.RawMessage, decode func(json.RawMessage) (T, error)) ([]T, error) {
	if len(raw) == 0 || string(raw) == "null" {
		return nil, nil
	}
	var items []json.RawMessage
	if err := json.Unmarshal(raw, &items); err != nil {
		return nil, err
	}
	values := make([]T, len(items))
	for i, item := range items {
		value, err := decode(item)
		if err != nil {
			return nil, err
		}
		values[i] = value
	}
	return values, nil
}`)
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, `func decodeType(raw json.RawMessage) (string, error) {
	var value struct{ Type string }
	if err := json.Unmarshal(raw, &value); err != nil {
		return "", err
	}
	return value.Type, nil
}`)
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, `func decodeDeref[T any](decode func(json.RawMessage) (*T, error)) func(json.RawMessage) (T, error) {
	return func(raw json.RawMessage) (T, error) {
		value, err := decode(raw)
		if err != nil {
			return *new(T), err
		}
		if value == nil {
			return *new(T), fmt.Errorf("unexpected null value")
		}
		return *value, nil
	}
}`)
	fmt.Fprintln(buf)

	var operatorTypes []string
	for name := range operators {
		operatorTypes = append(operatorTypes, name)
	}
	sort.Strings(operatorTypes)
	for _, name := range operatorTypes {
		fmt.Fprintf(buf, "func decode%s(raw json.RawMessage) (syntax.%s, error) {\n", name, name)
		fmt.Fprintln(buf, "\tvalue, err := decodeUint(raw)")
		fmt.Fprintf(buf, "\treturn syntax.%s(value), err\n", name)
		fmt.Fprintln(buf, "}")
		fmt.Fprintln(buf)
	}

	for _, name := range allTypes {
		info := structs[name]
		fmt.Fprintf(buf, "func decode%s(raw json.RawMessage) (*syntax.%s, error) {\n", name, name)
		fmt.Fprintln(buf, "\tvar fields map[string]json.RawMessage")
		fmt.Fprintln(buf, "\tif err := json.Unmarshal(raw, &fields); err != nil { return nil, err }")
		fmt.Fprintf(buf, "\tv := &syntax.%s{}\n", name)
		fmt.Fprintln(buf, "\tvar err error")
		for _, f := range info.fields {
			expr := decoderExpr(f.typ, interfaces, "fields["+strconv.Quote(jsName(f.name))+"]")
			fmt.Fprintf(buf, "\tv.%s, err = %s\n", f.name, expr)
			fmt.Fprintf(buf, "\tif err != nil { return nil, fmt.Errorf(\"%%s: %%w\", %q, err) }\n", f.name)
		}
		fmt.Fprintln(buf, "\treturn v, nil")
		fmt.Fprintln(buf, "}")
		fmt.Fprintln(buf)
	}

	for _, name := range []string{"Command", "WordPart", "Loop", "ArithmExpr", "TestExpr"} {
		types := interfaces[name]
		fmt.Fprintf(buf, "func decode%s(raw json.RawMessage) (syntax.%s, error) {\n", name, name)
		fmt.Fprintln(buf, "\tif len(raw) == 0 || string(raw) == \"null\" { return nil, nil }")
		fmt.Fprintln(buf, "\tvar fields map[string]json.RawMessage")
		fmt.Fprintln(buf, "\tif err := json.Unmarshal(raw, &fields); err != nil { return nil, err }")
		fmt.Fprintln(buf, "\ttypeName, err := decodeType(raw)")
		fmt.Fprintln(buf, "\tif err != nil { return nil, err }")
		fmt.Fprintln(buf, "\tswitch typeName {")
		for _, typ := range types {
			fmt.Fprintf(buf, "\tcase %q:\n\t\treturn decode%s(raw)\n", typ, typ)
		}
		fmt.Fprintf(buf, "\tdefault:\n\t\treturn nil, fmt.Errorf(\"unsupported syntax.%s type %%q\", typeName)\n", name)
		fmt.Fprintln(buf, "\t}")
		fmt.Fprintln(buf, "}")
		fmt.Fprintln(buf)
	}

	fmt.Fprintln(buf, "// DecodeNode decodes the typed JSON emitted by EncodeNode.")
	fmt.Fprintln(buf, "func DecodeNode(data []byte) (syntax.Node, error) {")
	fmt.Fprintln(buf, "\ttypeName, err := decodeType(data)")
	fmt.Fprintln(buf, "\tif err != nil { return nil, err }")
	fmt.Fprintln(buf, "\tswitch typeName {")
	for _, name := range allTypes {
		if !structs[name].isNode {
			continue
		}
		fmt.Fprintf(buf, "\tcase %q:\n\t\treturn decode%s(data)\n", name, name)
	}
	fmt.Fprintln(buf, "\tdefault:\n\t\treturn nil, fmt.Errorf(\"unsupported syntax.Node type %q\", typeName)")
	fmt.Fprintln(buf, "\t}")
	fmt.Fprintln(buf, "}")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, "// DecodeFile decodes a shell syntax tree into a File.")
	fmt.Fprintln(buf, "func DecodeFile(data []byte) (*syntax.File, error) {")
	fmt.Fprintln(buf, "\tnode, err := DecodeNode(data)")
	fmt.Fprintln(buf, "\tif err != nil { return nil, err }")
	fmt.Fprintln(buf, "\tfile, ok := node.(*syntax.File)")
	fmt.Fprintln(buf, "\tif !ok { return nil, fmt.Errorf(\"expected File, got %T\", node) }")
	fmt.Fprintln(buf, "\treturn file, nil")
	fmt.Fprintln(buf, "}")
}

func decoderExpr(typ string, interfaces map[string][]string, expr string) string {
	switch typ {
	case "string":
		return "decodeString(" + expr + ")"
	case "bool":
		return "decodeBool(" + expr + ")"
	case "Pos":
		return "decodePos(" + expr + ")"
	case "uint":
		return "decodeUint(" + expr + ")"
	case "int":
		return "decodeInt(" + expr + ")"
	case "OptState":
		return "decodeInteger[syntax.OptState](" + expr + ")"
	}
	if strings.HasPrefix(typ, "[]") {
		el := strings.TrimPrefix(typ, "[]")
		if strings.HasPrefix(el, "*") {
			el = strings.TrimPrefix(el, "*")
			return "decodeList(" + expr + ", decode" + el + ")"
		}
		if _, ok := interfaces[el]; ok {
			return "decodeList(" + expr + ", decode" + el + ")"
		}
		return "decodeList(" + expr + ", decodeDeref(decode" + el + "))"
	}
	if strings.HasPrefix(typ, "*") {
		return "decodePtr(" + expr + ", decode" + strings.TrimPrefix(typ, "*") + ")"
	}
	if _, ok := interfaces[typ]; ok {
		return "decode" + typ + "(" + expr + ")"
	}
	return "decode" + typ + "(" + expr + ")"
}

func writePatcher(buf *bytes.Buffer, structs map[string]*typeInfo, allTypes []string, operators map[string]map[string]string) {
	fmt.Fprintln(buf, "// Code generated by scripts/gen-encoder; DO NOT EDIT.")
	fmt.Fprintln(buf, "package processor")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, "import (")
	fmt.Fprintln(buf, "\t\"encoding/json\"")
	fmt.Fprintln(buf, "\t\"fmt\"")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, "\t\"mvdan.cc/sh/v3/syntax\"")
	fmt.Fprintln(buf, ")")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, "// NodeTypeName returns the JS node type for a syntax node.")
	fmt.Fprintln(buf, "func NodeTypeName(node syntax.Node) string {")
	fmt.Fprintln(buf, "\tswitch node.(type) {")
	for _, name := range allTypes {
		if !structs[name].isNode {
			continue
		}
		fmt.Fprintf(buf, "\tcase *syntax.%s:\n\t\treturn %q\n", name, name)
	}
	fmt.Fprintln(buf, "\tdefault:\n\t\treturn \"\"")
	fmt.Fprintln(buf, "\t}")
	fmt.Fprintln(buf, "}")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, "// PatchScalar applies a scalar field update to a syntax node.")
	fmt.Fprintln(buf, "func PatchScalar(node syntax.Node, field string, raw json.RawMessage) error {")
	fmt.Fprintln(buf, "\tswitch n := node.(type) {")
	for _, name := range allTypes {
		info := structs[name]
		if !info.isNode {
			continue
		}
		fmt.Fprintf(buf, "\tcase *syntax.%s:\n\t\tswitch field {\n", name)
		for _, f := range info.fields {
			goType := patchType(f.typ, structs, operators)
			if goType == "" {
				continue
			}
			fmt.Fprintf(buf, "\t\tcase %q:\n", jsName(f.name))
			fmt.Fprintf(buf, "\t\t\tvar value %s\n", goType)
			fmt.Fprintln(buf, "\t\t\tif err := json.Unmarshal(raw, &value); err != nil { return err }")
			fmt.Fprintf(buf, "\t\t\tn.%s = value\n", f.name)
			fmt.Fprintln(buf, "\t\t\treturn nil")
		}
		fmt.Fprintln(buf, "\t\t}")
	}
	fmt.Fprintln(buf, "\t}")
	fmt.Fprintln(buf, "\treturn fmt.Errorf(\"unsupported scalar patch %s.%s\", NodeTypeName(node), field)")
	fmt.Fprintln(buf, "}")
}

func patchType(typ string, structs map[string]*typeInfo, operators map[string]map[string]string) string {
	switch typ {
	case "string", "bool", "int", "uint":
		return typ
	}
	if _, ok := operators[typ]; ok {
		return "syntax." + typ
	}
	if typ == "OptState" {
		return "syntax.OptState"
	}
	if _, ok := structs[typ]; ok {
		return ""
	}
	return ""
}
