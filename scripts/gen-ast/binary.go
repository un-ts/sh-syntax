func writeBinaryString(buf *bytes.Buffer, value string) {
	writeBinaryUint(buf, uint64(len(value)))
	buf.WriteString(value)
}

func writeBinaryBool(buf *bytes.Buffer, value bool) {
	if value { buf.WriteByte(1) } else { buf.WriteByte(0) }
}

func writeBinaryPos(buf *bytes.Buffer, value syntax.Pos) {
	writeBinaryUint(buf, uint64(value.Offset()))
	writeBinaryUint(buf, uint64(value.Line()))
	column := uint(0)
	if value.Col() > 0 { column = value.Col() - 1 }
	writeBinaryUint(buf, uint64(column))
	writeBinaryBool(buf, value.IsRecovered())
}

type binaryReader struct {
	data []byte
	offset int
}

func (r *binaryReader) uint() (uint64, error) {
	value, n := binary.Uvarint(r.data[r.offset:])
	if n <= 0 { return 0, fmt.Errorf("invalid varint") }
	r.offset += n
	return value, nil
}

func (r *binaryReader) string() (string, error) {
	length, err := r.uint(); if err != nil { return "", err }
	if length > uint64(len(r.data)-r.offset) { return "", fmt.Errorf("string exceeds payload") }
	value := string(r.data[r.offset:r.offset+int(length)])
	r.offset += int(length)
	return value, nil
}

func (r *binaryReader) bool() (bool, error) {
	if r.offset >= len(r.data) { return false, fmt.Errorf("missing bool") }
	value := r.data[r.offset] != 0
	r.offset++
	return value, nil
}

func (r *binaryReader) pos() (syntax.Pos, error) {
	offset, err := r.uint(); if err != nil { return syntax.Pos{}, err }
	line, err := r.uint(); if err != nil { return syntax.Pos{}, err }
	column, err := r.uint(); if err != nil { return syntax.Pos{}, err }
	recovered, err := r.bool(); if err != nil { return syntax.Pos{}, err }
	if recovered { return syntax.NewPos(0, 0, 0), nil }
	if offset != 0 || line != 0 { column++ }
	return syntax.NewPos(uint(offset), uint(line), uint(column)), nil
}

