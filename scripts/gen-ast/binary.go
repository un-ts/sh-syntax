func binaryNodeTypes(allTypes []string, structs map[string]*typeInfo) []string {
	var names []string
	for _, name := range allTypes {
		if structs[name].isNode {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	return names
}

func binaryRef(name string, nullable bool) string {
	return fmt.Sprintf(`{"k":"ref","t":%q,"n":%t}`, name, nullable)
}

func binaryFieldTS(typ string, interfaces map[string][]string) string {
	switch typ {
	case "string":
		return `{"k":"string"}`
	case "bool":
		return `{"k":"bool"}`
	case "Pos":
		return `{"k":"pos"}`
	case "Node":
		return `{"k":"iface","t":"Node"}`
	}
	if strings.HasPrefix(typ, "[]") {
		el := strings.TrimPrefix(typ, "[]")
		if strings.HasPrefix(el, "*") {
			return fmt.Sprintf(`{"k":"slice","e":%s}`, binaryRef(strings.TrimPrefix(el, "*"), true))
		}
		if _, ok := interfaces[el]; ok {
			return fmt.Sprintf(`{"k":"slice","e":{"k":"iface","t":%q}}`, el)
		}
		return fmt.Sprintf(`{"k":"slice","e":%s}`, binaryRef(el, false))
	}
	if strings.HasPrefix(typ, "*") {
		return binaryRef(strings.TrimPrefix(typ, "*"), true)
	}
	if _, ok := interfaces[typ]; ok {
		return fmt.Sprintf(`{"k":"iface","t":%q}`, typ)
	}
	return `{"k":"uint"}`
}

func writeWireSchema(structs map[string]*typeInfo, allTypes []string, interfaces map[string][]string) {
	var b strings.Builder
	b.WriteString("// Code generated by scripts/gen-ast; DO NOT EDIT.\n")
	b.WriteString("export interface WireField { k: 'string' | 'bool' | 'uint' | 'pos' | 'ref' | 'iface' | 'slice'; t?: string; n?: boolean; e?: WireField }\n")
	b.WriteString("export const WIRE_TYPES: Record<string, number> = {\n")
	for i, name := range binaryNodeTypes(allTypes, structs) {
		fmt.Fprintf(&b, "  %q: %d,\n", name, i+1)
	}
	b.WriteString("} as const\n\n")
	b.WriteString("export const WIRE_SCHEMA: Record<string, { node: boolean; fields: [string, WireField][] }> = {\n")
	for _, name := range allTypes {
		info := structs[name]
		fmt.Fprintf(&b, "  %q: { node: %t, fields: [\n", name, info.isNode)
		for _, f := range info.fields {
			fmt.Fprintf(&b, "    [%q, %s],\n", jsName(f.name), binaryFieldTS(f.typ, interfaces))
		}
		b.WriteString("  ] },\n")
	}
	b.WriteString("} as const\n")
	if err := os.WriteFile("src/wire-schema.ts", []byte(b.String()), 0o644); err != nil {
		fatalf("write wire schema: %v", err)
	}
}

