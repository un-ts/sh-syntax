func binaryWriteField(typ, expr string, interfaces map[string][]string) string {
	switch {
	case typ == "string":
		return fmt.Sprintf("writeBinaryString(buf, %s)", expr)
	case typ == "bool":
		return fmt.Sprintf("writeBinaryBool(buf, %s)", expr)
	case typ == "Pos":
		return fmt.Sprintf("writeBinaryPos(buf, %s)", expr)
	case strings.HasPrefix(typ, "[]"):
		el := strings.TrimPrefix(typ, "[]")
		if strings.HasPrefix(el, "*") {
			name := strings.TrimPrefix(el, "*")
			return fmt.Sprintf("writeBinaryUint(buf, uint64(len(%s))); for _, item := range %s { if item == nil { writeBinaryBool(buf, false) } else { writeBinaryBool(buf, true); write%sBinary(buf, item) } }", expr, expr, name)
		}
		if _, ok := interfaces[el]; ok {
			return fmt.Sprintf("writeBinaryUint(buf, uint64(len(%s))); for _, item := range %s { write%sBinary(buf, item) }", expr, expr, el)
		}
		return fmt.Sprintf("writeBinaryUint(buf, uint64(len(%s))); for i := range %s { write%sBinary(buf, &%s[i]) }", expr, expr, el, expr)
	case strings.HasPrefix(typ, "*"):
		name := strings.TrimPrefix(typ, "*")
		return fmt.Sprintf("if %s == nil { writeBinaryBool(buf, false) } else { writeBinaryBool(buf, true); write%sBinary(buf, %s) }", expr, name, expr)
	}
	if _, ok := interfaces[typ]; ok {
		return fmt.Sprintf("write%sBinary(buf, %s)", typ, expr)
	}
	return fmt.Sprintf("writeBinaryUint(buf, uint64(%s))", expr)
}

func binaryReadField(typ, target string, interfaces map[string][]string) []string {
	switch {
	case typ == "string":
		return []string{fmt.Sprintf("value, err := r.string(); if err != nil { return nil, err }; %s = value", target)}
	case typ == "bool":
		return []string{fmt.Sprintf("value, err := r.bool(); if err != nil { return nil, err }; %s = value", target)}
	case typ == "Pos":
		return []string{fmt.Sprintf("value, err := r.pos(); if err != nil { return nil, err }; %s = value", target)}
	case strings.HasPrefix(typ, "[]"):
		el := strings.TrimPrefix(typ, "[]")
		if strings.HasPrefix(el, "*") {
			name := strings.TrimPrefix(el, "*")
			return []string{fmt.Sprintf("count, err := r.count(); if err != nil { return nil, err }; %s = make([]*syntax.%s, 0, count); for i := 0; i < count; i++ { present, err := r.bool(); if err != nil { return nil, err }; if !present { return nil, fmt.Errorf(\"null element\") }; item, err := read%sBinary(r); if err != nil { return nil, err }; %s = append(%s, item) }", target, name, name, target, target)}
		}
		if _, ok := interfaces[el]; ok {
			return []string{fmt.Sprintf("count, err := r.count(); if err != nil { return nil, err }; %s = make([]syntax.%s, 0, count); for i := 0; i < count; i++ { item, err := read%sBinary(r); if err != nil { return nil, err }; %s = append(%s, item) }", target, el, el, target, target)}
		}
		return []string{fmt.Sprintf("count, err := r.count(); if err != nil { return nil, err }; %s = make([]syntax.%s, 0, count); for i := 0; i < count; i++ { item, err := read%sBinary(r); if err != nil { return nil, err }; %s = append(%s, *item) }", target, el, el, target, target)}
	case strings.HasPrefix(typ, "*"):
		name := strings.TrimPrefix(typ, "*")
		return []string{fmt.Sprintf("present, err := r.bool(); if err != nil { return nil, err }; if present { item, err := read%sBinary(r); if err != nil { return nil, err }; %s = item }", name, target)}
	}
	if _, ok := interfaces[typ]; ok {
		return []string{fmt.Sprintf("item, err := read%sBinary(r); if err != nil { return nil, err }; %s = item", typ, target)}
	}
	return []string{fmt.Sprintf("value, err := r.uint(); if err != nil { return nil, err }; %s = syntax.%s(value)", target, typ)}
}
